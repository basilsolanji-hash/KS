    public static IReadOnlyList<string> Categories => Articles.Select(a => a.Category).Distinct().ToList();

    /// <summary>Подсказка по текущему экрану: статья, чей адрес раздела совпадает с началом пути.</summary>
    public static HelpArticle? ForRoute(string? route)
    {
        var path = (route ?? string.Empty).Trim('/').Split('?', '#')[0];
        return Articles
            .SelectMany(a => a.Routes.Select(r => (Article: a, Route: r)))
            .Where(x => x.Route.Length == 0 ? path.Length == 0 : path == x.Route || path.StartsWith(x.Route + "/", StringComparison.Ordinal))
            .OrderByDescending(x => x.Route.Length)
            .Select(x => x.Article)
            .FirstOrDefault();
    }

    /// <summary>Поиск по словам: совпадение в заголовке весит больше, чем в тексте.</summary>
    public static IReadOnlyList<HelpArticle> Search(string? query, int take = 5)
    {
        var words = (query ?? string.Empty).ToLowerInvariant()
            .Split([' ', ',', '.', '?', '!', ':', ';', '«', '»', '"'], StringSplitOptions.RemoveEmptyEntries)
            .Where(w => w.Length >= 3 && !StopWords.Contains(w)).Select(Stem).Distinct().ToList();
        if (words.Count == 0)
        {
            return [];
        }

        return Articles
            .Select(a => (Article: a, Score: words.Sum(w =>
                (a.Title.Contains(w, StringComparison.OrdinalIgnoreCase) ? 3 : 0) + (a.Text.Contains(w, StringComparison.OrdinalIgnoreCase) ? 1 : 0))))
            .Where(x => x.Score > 0)
            .OrderByDescending(x => x.Score)
            .Take(take)
            .Select(x => x.Article)
            .ToList();
    }

    /// <summary>Служебные слова вопроса не говорят о теме и не участвуют в поиске.</summary>
    private static readonly HashSet<string> StopWords =
    [
        "как", "что", "где", "для", "это", "или", "при", "нет", "мне", "меня", "можно", "нужно", "надо", "сделать", "делать",
        "почему", "зачем", "когда", "какой", "какая", "какие", "если", "чтобы", "все", "всё", "его", "она", "они", "этот", "эта",
    ];

    /// <summary>Грубое отсечение окончаний: «остатки», «остатков», «остаток» находят друг друга.</summary>
    private static string Stem(string word) => word.Length > 5 ? word[..^2] : word;
